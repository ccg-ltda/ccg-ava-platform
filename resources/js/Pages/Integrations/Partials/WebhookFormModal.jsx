import { useForm } from '@inertiajs/react';
import InputError from '@/Components/InputError';
import InputLabel from '@/Components/InputLabel';
import Checkbox from '@/Components/Checkbox';
import Modal from '@/Components/Modal';
import PrimaryButton from '@/Components/PrimaryButton';
import SecondaryButton from '@/Components/SecondaryButton';
import TextInput from '@/Components/TextInput';

/** The events of the catalog grouped the way the server groups them (Conversaciones, Reservas, Pedidos). */
export const groupEvents = (events) =>
    events.reduce((groups, event) => {
        (groups[event.group] ||= []).push(event);

        return groups;
    }, {});

/**
 * Create / edit a webhook of the Workspace. The signing secret is never part of this form: it is generated by the server and shown once after creating (or rotating).
 * The destination is checked by the server (https, public addresses only) and again before every delivery.
 */
export default function WebhookFormModal({ webhook, events, onClose }) {
    const editing = Boolean(webhook);
    const form = useForm({ name: webhook?.name ?? '', url: webhook?.url ?? '', events: webhook?.events ?? [] });
    const { data, setData, errors } = form;
    const groups = groupEvents(events);

    const toggle = (key, checked) => setData('events', checked ? [...data.events, key] : data.events.filter((event) => event !== key));
    const toggleGroup = (group, checked) => {
        const keys = groups[group].map((event) => event.key);
        setData('events', checked ? [...new Set([...data.events, ...keys])] : data.events.filter((event) => !keys.includes(event)));
    };

    const submit = (event) => {
        event.preventDefault();
        const options = { preserveScroll: true, onSuccess: onClose };

        if (editing) {
            form.put(route('integrations.webhooks.update', webhook.id), options);
        } else {
            form.post(route('integrations.webhooks.store'), options);
        }
    };

    return (
        <Modal show onClose={onClose} maxWidth="3xl" scrollable>
            <form onSubmit={submit} noValidate className="flex min-h-0 flex-1 flex-col">
                <header className="border-b border-line px-5 py-4 sm:px-8 sm:py-5">
                    <h2 className="text-lg font-bold text-ink">{editing ? 'Editar webhook' : 'Nuevo webhook'}</h2>
                    <p className="mt-1 text-sm text-ink-muted">Ava enviará un aviso firmado a esta dirección cada vez que ocurra uno de los eventos que elijas.</p>
                </header>

                <div className="min-h-0 flex-1 space-y-6 overflow-y-auto px-5 py-6 sm:px-8">
                    <div>
                        <InputLabel htmlFor="wh_name" value="Nombre" />
                        <TextInput id="wh_name" className="mt-1" value={data.name} onChange={(e) => setData('name', e.target.value)} invalid={Boolean(errors.name)} maxLength={80} autoComplete="off" />
                        <InputError message={errors.name} className="mt-1" />
                    </div>

                    <div>
                        <InputLabel htmlFor="wh_url" value="Dirección de destino (https)" />
                        <TextInput id="wh_url" className="mt-1" value={data.url} onChange={(e) => setData('url', e.target.value)} placeholder="https://mi-sistema.com/webhooks/ava" invalid={Boolean(errors.url)} maxLength={2048} autoComplete="off" inputMode="url" />
                        <InputError message={errors.url} className="mt-1" />
                        <p className="mt-1.5 text-xs text-ink-muted">Debe ser una dirección pública con https. No se aceptan direcciones internas, locales ni con usuario y contraseña. Si el destino responde con una redirección, no se sigue.</p>
                    </div>

                    <fieldset>
                        <legend className="text-sm font-medium text-ink">Eventos</legend>
                        <p className="mt-1 text-sm text-ink-muted">Elige los que quieres recibir. Cada aviso lleva identificadores, estados y fechas; nunca nombres, teléfonos, correos ni el texto de los mensajes.</p>
                        <InputError message={errors.events || errors['events.0']} className="mt-1" />

                        <div className="mt-3 space-y-4">
                            {Object.entries(groups).map(([group, items]) => {
                                const all = items.every((event) => data.events.includes(event.key));

                                return (
                                    <div key={group} className="rounded-xl border border-line bg-canvas/40 p-4">
                                        <label className="flex items-center gap-2 text-sm font-bold text-ink">
                                            <Checkbox checked={all} onChange={(e) => toggleGroup(group, e.target.checked)} aria-label={`Todos los eventos de ${group}`} />
                                            {group}
                                        </label>
                                        <ul className="mt-3 space-y-3">
                                            {items.map((event) => (
                                                <li key={event.key}>
                                                    <label className="flex items-start gap-2.5 text-sm">
                                                        <Checkbox className="mt-0.5" checked={data.events.includes(event.key)} onChange={(e) => toggle(event.key, e.target.checked)} />
                                                        <span className="min-w-0">
                                                            <span className="font-semibold text-ink">{event.label}</span> <code className="font-mono text-xs text-ink-muted">{event.key}</code>
                                                            <span className="block text-ink-muted">{event.description}</span>
                                                        </span>
                                                    </label>
                                                </li>
                                            ))}
                                        </ul>
                                    </div>
                                );
                            })}
                        </div>
                    </fieldset>
                </div>

                <div className="flex justify-end gap-3 border-t border-line bg-card px-5 py-4 sm:px-8">
                    <SecondaryButton type="button" onClick={onClose}>
                        Cancelar
                    </SecondaryButton>
                    <PrimaryButton type="submit" disabled={form.processing}>
                        {form.processing ? 'Guardando...' : editing ? 'Guardar cambios' : 'Crear webhook'}
                    </PrimaryButton>
                </div>
            </form>
        </Modal>
    );
}
